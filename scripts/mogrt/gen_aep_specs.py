#!/usr/bin/env python3
"""Generate src/Services/mogrt/aep/specData.js from py_aep's synthesis spec tables (MIT).

py_aep (and ExtendScript) report a fixed set of properties for every layer / group even when the .aep only stores the
ones that differ from the defaults ("synthetic" nodes). The Scene JSON oracle contains them, and the evaluator relies on
them (e.g. the default Position = comp centre). This script exports the spec tables as rows; the JS reader
(src/Services/mogrt/aep/synth.js) re-creates the same nodes.

Run:  python scripts/mogrt/gen_aep_specs.py
Rows: ['p', matchName, name, valueType, dims, isSpatial, value, min, max, minMajor, specMin, specMax, boundsAreHints]
      ['g', matchName, name, enabled, groupType, minMajor]
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import aep_to_scene as oracle  # noqa: E402
from py_aep import parse  # noqa: E402
from py_aep.synthesis import property as sp  # noqa: E402
from py_aep.models.properties import property_group as pg  # noqa: E402
from py_aep.models.properties.property import Property  # noqa: E402
from py_aep.models.properties.property_group import PropertyGroup  # noqa: E402

here = os.path.dirname(os.path.abspath(__file__))
sample = os.path.join(here, "..", "..", "test-assets", "mogrt", "steam", "project.aep")
proj = parse(sample).project
comp = [i for i in proj.items.values() if hasattr(i, "layers")][0]
parent = None
for layer in comp.layers:
    try:
        parent = layer["ADBE Transform Group"]
        break
    except Exception:
        continue
assert parent is not None

STD_KEYS = {"kind", "matchName", "synthetic", "name", "enabled", "valueType", "dimensions", "isSpatial", "value",
            "keyframes", "expression", "expressionEnabled", "min", "max"}


def row(spec):
    if isinstance(spec, sp.GroupSpec):
        g = PropertyGroup._new(spec.match_name, spec.auto_name, 2, parent_property=parent, synthetic=True,
                               enable_flags=spec.enable_flags)
        enabled = bool(g.enabled)
        gt = "indexed" if g.property_type == oracle.PropertyType.INDEXED_GROUP else "named"
        return ["g", spec.match_name, spec.auto_name, enabled, gt, spec.min_major]
    p = Property._new(spec, 2, parent_property=parent, synthetic=True)
    n = oracle.prop_json(p, "spec")
    extra = set(n) - STD_KEYS
    assert not extra, (spec.match_name, extra)
    assert n.get("controlType") is None
    assert n["keyframes"] == [] and n["expression"] is None and n["enabled"] is True, spec.match_name
    return ["p", spec.match_name, n["name"], n["valueType"], n["dimensions"], n["isSpatial"], n["value"],
            n.get("min"), n.get("max"), spec.min_major, spec.min_value, spec.max_value,
            1 if spec.chunk_bounds_are_hints else 0]


containers = {}


def add(k, specs):
    containers[k] = [row(s) for s in specs]


for k, specs in sp._GROUP_CHILD_SPECS.items():
    add(k, specs)
for k, specs in sp._LAYER_STYLE_CHILD_SPECS.items():
    add(k, specs)

data = {
    "containers": containers,
    "top": [row(s) for s in sp._TOP_LEVEL_SPECS],
    "meshTop": [row(s) for s in sp._PARAMETRIC_MESH_TOP_LEVEL_SPECS],
    "transform": [row(s) for s in sp._TRANSFORM_SPECS],
    "fixed": {k: v for k, v in sp._TRANSFORM_FIXED_DEFAULTS.items()},
    "skip": {
        "text": sorted(sp._SKIP_FOR_TEXT), "shape": sorted(sp._SKIP_FOR_SHAPE), "av": sorted(sp._SKIP_FOR_REGULAR_AV),
        "camera": sorted(sp._SKIP_FOR_CAMERA), "light": sorted(sp._SKIP_FOR_LIGHT),
    },
}
mm = {k: [v[0], v[1]] for k, v in pg._PROPERTY_MIN_MAX.items()}

dst = os.path.normpath(os.path.join(here, "..", "..", "src", "Services", "mogrt", "aep", "specData.js"))
with open(dst, "w", encoding="utf-8") as f:
    f.write("// GENERATED by scripts/mogrt/gen_aep_specs.py from py_aep.synthesis (MIT). Do not edit.\n")
    f.write("// Rows: ['p', matchName, name, valueType, dims, isSpatial, value, min, max, minMajor, specMin, specMax, boundsAreHints]\n")
    f.write("//       ['g', matchName, name, enabled, groupType, minMajor]\n")
    f.write("export const SPECS = " + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n")
    f.write("export const PROPERTY_MIN_MAX = " + json.dumps(mm, separators=(",", ":")) + ";\n")
print("wrote", dst, os.path.getsize(dst), "bytes;", len(containers), "containers")

