# Dev tool (not shipped): regenerate src/Services/interchange/aafTemplate.js, the standard AAF MetaDictionary
# (class / property / type definitions) and Dictionary (data / container / codec definitions) that every AAF file
# carries. The data are the AAF object model's definitions; they are read here from an empty file written by
# pyaaf2 (MIT, https://github.com/markreidvfx/pyaaf2). EditorStage itself only copies the bytes (aaf.js).
# Usage: python -m pip install pyaaf2 ; python scripts/aaf/make_template.py
import base64, json, os, struct, sys, tempfile
import aaf2
from aaf2 import cfb

out = os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'Services', 'interchange', 'aafTemplate.js')
tmp = os.path.join(tempfile.mkdtemp(), 'empty.aaf')
with aaf2.open(tmp, 'w') as f:
    pass
f = cfb.CompoundFileBinary(open(tmp, 'rb'), 'rb')

def node(e, path):
    if e.isdir():
        kids = sorted(f.listdir(e), key=lambda c: c.name)
        return {'n': e.name, 'c': str(e.class_id), 'k': [node(c, path + '/' + c.name) for c in kids]}
    return {'n': e.name, 'd': base64.b64encode(f.open(path).read()).decode('ascii')}

root = f.find('/')
meta = next(c for c in f.listdir(root) if c.name.startswith('MetaDictionary'))
header = next(c for c in f.listdir(root) if c.name.startswith('Header'))
dic = next(c for c in f.listdir(header) if c.name.startswith('Dictionary'))
refs = f.open('/referenced properties').read()
assert refs[0] == 0x4c
n_paths, n_pids = struct.unpack('<HI', refs[1:7])
pids = struct.unpack('<%dH' % n_pids, refs[7:7 + 2 * n_pids])
paths, cur = [], []
for p in pids:
    if p:
        cur.append(p)
    else:
        paths.append(cur); cur = []
assert len(paths) == n_paths
tpl = {
    'source': 'pyaaf2 %s empty file' % getattr(aaf2, '__version__', ''),
    'rootClass': str(root.class_id),
    'metaDictionary': node(meta, '/' + meta.name),
    'dictionary': node(dic, '/' + header.name + '/' + dic.name),
    'weakrefPaths': paths,
}
with open(out, 'w') as o:
    o.write('// Generated by scripts/aaf/make_template.py from pyaaf2 (MIT) - do not edit.\nexport default ')
    json.dump(tpl, o, separators=(',', ':'))
    o.write(';\n')
print('wrote', out, os.path.getsize(out), 'bytes;', len(paths), 'weak reference paths')
